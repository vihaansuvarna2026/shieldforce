// Turn the translation files into the dictionaries the app loads, and check them.
//
//   i18n/en.json            every English text unit: { hash: { en, at } }  (npm run i18n:extract)
//   i18n/<lang>/*.json      translations: { hash: "translated text" }      (any number of files)
//   → js/i18n/<lang>.js     what the app loads for that language
//   → i18n/review/<lang>.csv a sheet for native speakers to check: screen, English, translation
//
// A translation must keep exactly the placeholders of its English: <1>…</1> (bold text,
// links), <2/> (icons, names, values) and {0} (numbers). Ones that don't are reported and
// left out, so the English shows instead of a broken sentence.
// Exit code 1 if any language is incomplete or has errors (use --allow-missing to relax).
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dir = join(root, "i18n");
const LANGS = ["hi", "bn", "mr", "te", "ta", "gu", "ur", "kn", "or", "ml", "pa", "as", "ne"];
const allowMissing = process.argv.includes("--allow-missing");

const en = JSON.parse(readFileSync(join(dir, "en.json"), "utf8"));
const tokens = (s) => (s.match(/<\/?\d+\/?>|\{\w+\}/g) || []).sort().join(" ");
function balanced(s) {
  const stack = [];
  for (const m of s.matchAll(/<(\/?)(\d+)(\/?)>/g)) {
    if (m[3]) continue;
    if (!m[1]) stack.push(m[2]);
    else if (stack.pop() !== m[2]) return false;
  }
  return stack.length === 0;
}
const plain = (s) => s.replace(/<\/?\d+\/?>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .replace(/&#123;/g, "{").replace(/&#125;/g, "}");
const csv = (s) => '"' + String(s).replace(/"/g, '""') + '"';

mkdirSync(join(root, "js", "i18n"), { recursive: true });
mkdirSync(join(dir, "review"), { recursive: true });
let failed = false;
const complete = [];
const total = Object.keys(en).length;

for (const lang of LANGS) {
  const ldir = join(dir, lang);
  const tr = {};
  if (existsSync(ldir)) {
    for (const f of readdirSync(ldir).filter((f) => f.endsWith(".json")).sort()) {
      Object.assign(tr, JSON.parse(readFileSync(join(ldir, f), "utf8")));
    }
  }
  const dict = {}, bad = [], missing = [];
  for (const [h, u] of Object.entries(en)) {
    const t = tr[h];
    if (t == null || t === "") { missing.push(h); continue; }
    if (tokens(t) !== tokens(u.en) || !balanced(t)) { bad.push(`${h}: "${u.en.slice(0, 60)}" → "${t.slice(0, 60)}"`); continue; }
    dict[h] = t;
  }
  const stale = Object.keys(tr).filter((h) => !en[h]).length;
  writeFileSync(join(root, "js", "i18n", lang + ".js"),
    `/* Shield Force — ${lang} translations, generated by scripts/i18n/build.mjs from i18n/${lang}/ */\n` +
    `window.SF_I18N_DICT=${JSON.stringify(dict)};\n`);
  const rows = ["key,screen,English,Translation,Reviewer correction"];
  for (const [h, u] of Object.entries(en)) rows.push([h, u.at, plain(u.en), plain(tr[h] || ""), ""].map(csv).join(","));
  writeFileSync(join(dir, "review", lang + ".csv"), "﻿" + rows.join("\n") + "\n");

  const pct = Math.floor((Object.keys(dict).length / total) * 1000) / 10;
  console.log(`${lang}: ${Object.keys(dict).length}/${total} (${pct}%)` +
    (missing.length ? `, ${missing.length} missing` : "") + (bad.length ? `, ${bad.length} with placeholder errors` : "") +
    (stale ? `, ${stale} no longer used` : ""));
  bad.slice(0, 8).forEach((b) => console.log("   ✗ " + b));
  if (bad.length || (missing.length && !allowMissing)) failed = true;
  if (!bad.length && !missing.length) complete.push(lang);
}
// offer in the app only the languages that are complete and error-free
const ready = ["en", ...complete];
const engine = join(root, "js", "i18n.js");
const src = readFileSync(engine, "utf8");
writeFileSync(engine, src.replace(/const READY = \[[^\]]*\];/, "const READY = " + JSON.stringify(ready) + ";"));
console.log("offered in the app:", ready.join(", "));
process.exit(failed ? 1 : 0);
